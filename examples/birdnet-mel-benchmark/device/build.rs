//! Build pipeline for the mel projection benchmark. Four generated modules —
//! one per (mode, branch):
//!
//!   dense_fc:  models/birdnet/stft/mel_2048.tflite / mel_1024.tflite
//!              (sliced out of BirdNET by slice_stft.py) through the normal
//!              psp-tc pipeline — the [96, bins] mel matrix as a dense FC,
//!              99%+ of whose MACs multiply by zero.
//!   banded_cb: the same projection built with PspModelBuilder as
//!              FullyConnectedCB over `make_mel`'s column-banded filterbank
//!              (regenerated from the reverse-engineered HTK parameters),
//!              plus the fused square-pow compression.
//!
//! The branch inputs are the STFT goldens (golden_<L>.bin), which are
//! bit-exactly what feeds this subgraph in the full model.

use std::path::{Path, PathBuf};
use std::process::Command;

const SLICER: &str = "examples/birdnet-stft-benchmark/slice_stft.py";
const ASSETS: &str = "models/birdnet/stft";
const N_WINDOWS: usize = 511;
const N_BANKS: usize = 96;

/// (fft_length, fmin, fmax) — the reverse-engineered filterbank ranges per
/// branch (docs/Custom Frontend.md), verified against the stored matrices by
/// psp-tc's `make_mel_matches_birdnet_stored_matrices`.
const BRANCHES: [(usize, f64, f64); 2] = [(2048, 0.0, 3000.0), (1024, 500.0, 15000.0)];
const SAMPLING_RATE: f64 = 48_000.0;

fn main() {
    let manifest_dir = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").unwrap());
    let out_dir = PathBuf::from(std::env::var("OUT_DIR").unwrap());
    let repo_root = manifest_dir.join("../../..");
    let assets = repo_root.join(ASSETS);

    println!("cargo:rerun-if-env-changed=BIRDNET_PYTHON");
    println!("cargo:rerun-if-changed={}", repo_root.join(SLICER).display());
    for (l, _, _) in BRANCHES {
        for f in [
            format!("mel_{l}.tflite"),
            format!("golden_{l}.bin"),
            format!("golden_mel_{l}.bin"),
        ] {
            println!("cargo:rerun-if-changed={}", assets.join(f).display());
        }
    }

    ensure_assets(&repo_root, &assets);

    let manifest: serde_json::Value = serde_json::from_str(
        &std::fs::read_to_string(assets.join("manifest.json")).unwrap(),
    )
    .unwrap();
    let pow_exponent = |fft_length: usize| -> f32 {
        manifest["branches"]
            .as_array()
            .unwrap()
            .iter()
            .find(|b| b["fft_length"].as_u64() == Some(fft_length as u64))
            .unwrap_or_else(|| panic!("no manifest entry for L={fft_length}"))["pow_exponent"]
            .as_f64()
            .unwrap() as f32
    };

    let (mut dense_arena, mut dense_blob) = (0usize, 0usize);
    let (mut cb_arena, mut cb_blob) = (0usize, 0usize);
    for (l, fmin, fmax) in BRANCHES {
        let bins = l / 2 + 1;
        let pow = pow_exponent(l);

        // Dense mode: the sliced .tflite through the standard pipeline.
        let dense_dir = out_dir.join("dense");
        std::fs::create_dir_all(&dense_dir).unwrap();
        let dense = psp_tc::compile_tflite_named(
            &assets.join(format!("mel_{l}.tflite")),
            &dense_dir,
            None,
            &format!("mel_dense_{l}"),
        )
        .unwrap_or_else(|e| panic!("psp-tc codegen (dense L={l}) failed: {e}"));
        dense_arena += dense.arena_size_floats * 4;
        dense_blob += dense.blob_bytes;

        // CB mode: banded matmul + fused square-pow, hand-built on the
        // builder. The filterbank is regenerated by make_mel (the point: it
        // can be rebuilt for the PSP's real 44.1 kHz later); its f32 values
        // land ~2e-5 off BirdNET's stored matrix, which the x^~0.22
        // compression amplifies to a few 1e-3 in the output — hence
        // banded_cb's looser golden gate. MEL_CB_USE_STORED=1 compresses the
        // stored matrix instead, isolating the CB kernel from the
        // regeneration: with it the error drops to dense-mode levels.
        let use_stored = std::env::var("MEL_CB_USE_STORED").is_ok_and(|v| v != "0");
        println!("cargo:rerun-if-env-changed=MEL_CB_USE_STORED");
        let mut b = psp_tc::PspModelBuilder::new();
        let fft = b.input(vec![N_WINDOWS, bins]);
        let out = if use_stored {
            let bytes = std::fs::read(assets.join(format!("mel_dense_{l}.bin"))).unwrap();
            let stored: Vec<f32> = bytes
                .chunks_exact(4)
                .map(|c| f32::from_le_bytes(c.try_into().unwrap()))
                .collect();
            let mel_mat = psp_tc::CBMatrix::from_bank_rows(&stored, N_BANKS, bins).unwrap();
            let matmul = b.fully_connected_cb(fft, &mel_mat);
            b.square_pow(matmul, pow)
        } else {
            psp_tc::mel_spectrogram(&mut b, fft, SAMPLING_RATE, fmin, fmax, N_BANKS, pow)
        };
        b.output(out);
        let mut model = b.finish();
        let cb_dir = out_dir.join("cb");
        std::fs::create_dir_all(&cb_dir).unwrap();
        let cb = psp_tc::compile_graph(&mut model, &cb_dir, &format!("mel_cb_{l}"))
            .unwrap_or_else(|e| panic!("psp-tc codegen (cb L={l}) failed: {e}"));
        cb_arena += cb.arena_size_floats * 4;
        cb_blob += cb.blob_bytes;

        // Branch input: the STFT golden, staged for include_bytes!.
        std::fs::copy(
            assets.join(format!("golden_{l}.bin")),
            out_dir.join(format!("input_{l}.bin")),
        )
        .unwrap();
    }

    let output_bytes = 2 * N_WINDOWS * N_BANKS * 4;
    let config = format!(
        "pub const N_WINDOWS: usize = {N_WINDOWS};\n\
         pub const N_BANKS: usize = {N_BANKS};\n\
         pub const DENSE_ARENA_BYTES: usize = {dense_arena};\n\
         pub const DENSE_BLOB_BYTES: usize = {dense_blob};\n\
         pub const CB_ARENA_BYTES: usize = {cb_arena};\n\
         pub const CB_BLOB_BYTES: usize = {cb_blob};\n\
         pub const OUTPUT_BYTES: usize = {output_bytes};\n",
    );
    std::fs::write(out_dir.join("bench_config.rs"), config).unwrap();

    println!(
        "cargo:warning=mel-bench dense_fc:  arena {dense_arena} B + blob {dense_blob} B"
    );
    println!("cargo:warning=mel-bench banded_cb: arena {cb_arena} B + blob {cb_blob} B");
}

/// Same convention as the STFT benchmark: regenerate the sliced models +
/// fixtures when missing, via `uv run` (or BIRDNET_PYTHON).
fn ensure_assets(repo_root: &Path, assets: &Path) {
    let mut needed: Vec<String> = vec!["manifest.json".into()];
    for (l, _, _) in BRANCHES {
        needed.push(format!("mel_{l}.tflite"));
        needed.push(format!("mel_dense_{l}.bin"));
        needed.push(format!("golden_{l}.bin"));
        needed.push(format!("golden_mel_{l}.bin"));
    }
    if needed.iter().all(|f| assets.join(f).exists()) {
        return;
    }

    let slicer = repo_root.join(SLICER);
    let mut cmd = match std::env::var("BIRDNET_PYTHON") {
        Ok(py) if !py.trim().is_empty() => {
            let mut c = Command::new(py);
            c.arg(&slicer);
            c
        }
        _ => {
            let mut c = Command::new("uv");
            c.arg("run").arg(&slicer);
            c
        }
    };
    let status = cmd.current_dir(repo_root).status().unwrap_or_else(|e| {
        panic!("failed to run {} ({e}). {PYTHON_HELP}", slicer.display())
    });
    assert!(status.success(), "slice_stft.py failed. {PYTHON_HELP}");
}

const PYTHON_HELP: &str = "Install uv, or set BIRDNET_PYTHON to a python that \
has ai-edge-litert (or tensorflow), numpy and flatbuffers installed. Requires \
models/birdnet/audio-model-int8.tflite (gitignored, downloaded separately).";
